static int kernel_calls, kernel_e0, kernel_nx, kernel_prec;
static float kernel_tx[3];
static const int* kernel_table;
extern "C" int __kernel_rem_pio2f(float* x, float* y, int e0, int nx, int prec, const int* ipio2) {
    ++kernel_calls; kernel_e0 = e0; kernel_nx = nx; kernel_prec = prec; kernel_table = ipio2;
    for (int i = 0; i < 3; ++i) kernel_tx[i] = x[i];
    y[0] = 0.25f; y[1] = 0.125f;
    return 5;
}
static int failures;
static void expect(bool ok, const char* what, double x = 0) {
    if (!ok) { std::fprintf(stderr, "fail: %s (x=%g)\n", what, x); ++failures; }
}
int main() {
    for (const Recorded& r : recorded) {
        const float x = from_bits(r.x);
        if ((to_bits(x) & 0x7fffffffu) > 0x43490f80u) continue;  // large path needs the kernel
        float y[2] = {-7.0f, -7.0f};
        const int n = __ieee754_rem_pio2f(x, y);
        expect(n == r.n && to_bits(y[0]) == r.y0 && to_bits(y[1]) == r.y1, "recorded n, y0, y1", x);
        const double residue = double(x) - n * (M_PI / 2);
        expect(std::fabs(residue - (double(y[0]) + double(y[1]))) < 1e-6 * (1 + std::fabs(x)) * 1e-1 + 4e-7, "y0+y1 is x - n*pi/2", x);
    }
    // npio2_hw is the high part of n*pi/2 for n = 1..32, low 8 bits cleared.
    for (int n = 1; n <= 32; ++n)
        expect((to_bits(static_cast<float>(n * (M_PI / 2))) & 0xffffff00u) == npio2_hw[n - 1], "npio2_hw entry", n);
    // two_over_pi holds the first bytes of 2/pi: check its leading value against double.
    {
        double v = 2.0 / M_PI; bool ok = true;
        for (int i = 0; i < 6; ++i) { v *= 256; const int b = int(v); v -= b; ok = ok && b == two_over_pi[i]; }
        expect(ok && two_over_pi[0] == 162 && two_over_pi[197] == 107, "two_over_pi leading bytes");
    }
    // Large arguments: tx split and the kernel call, for both signs.
    for (float x : {1000.0f, -1000.0f, 3.0e5f, 1.0e10f, -4.0e20f, 8.5e37f}) {
        kernel_calls = 0;
        float y[2];
        const int n = __ieee754_rem_pio2f(x, y);
        const int ix = to_bits(x) & 0x7fffffff;
        const int e0 = (ix >> 23) - 134;
        double z = std::ldexp(std::fabs((double)x), -e0);
        double tx[3];
        tx[0] = std::trunc(z); z = (z - tx[0]) * 256.0;
        tx[1] = std::trunc(z); z = (z - tx[1]) * 256.0;
        tx[2] = z;
        int nx = 3; while (tx[nx - 1] == 0.0) nx--;
        expect(kernel_calls == 1 && kernel_e0 == e0 && kernel_nx == nx && kernel_prec == 2 && kernel_table == two_over_pi, "kernel arguments", x);
        expect(kernel_tx[0] == (float)tx[0] && kernel_tx[1] == (float)tx[1] && kernel_tx[2] == (float)tx[2], "tx split", x);
        expect(x > 0 ? (n == 5 && y[0] == 0.25f && y[1] == 0.125f) : (n == -5 && y[0] == -0.25f && y[1] == -0.125f), "sign handling of kernel result", x);
    }
    // Trailing zero words are dropped: 2^30 has only tx[0] set.
    {
        kernel_calls = 0; float y[2];
        __ieee754_rem_pio2f(std::ldexp(1.0f, 30), y);
        expect(kernel_nx == 1, "trailing zeros trimmed");
    }
    if (!failures) std::puts("rem_pio2f ok");
    return failures ? 1 : 0;
}

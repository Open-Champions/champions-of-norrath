// Host comparison only. Not an EE build input.
#include <cstdio>
#include <cstring>

#include "assert_format.cpp"

int main() {
    // Bytes read from the target image, in the order they appear.
    static const unsigned char expected[] = {
        0x41, 0x73, 0x73, 0x65, 0x72, 0x74, 0x69, 0x6f, 0x6e, 0x20, 0x22, 0x25, 0x73, 0x22, 0x20, 0x66,
        0x61, 0x69, 0x6c, 0x65, 0x64, 0x20, 0x69, 0x6e, 0x20, 0x25, 0x73, 0x3a, 0x25, 0x64, 0x20, 0x20,
        0x63, 0x6f, 0x6e, 0x74, 0x65, 0x78, 0x74, 0x3a, 0x25, 0x73, 0x20, 0x28, 0x25, 0x78, 0x29, 0x0a, 0x00};
    if (sizeof(norrath_assert_format_view) != sizeof(expected) || std::memcmp(norrath_assert_format_view, expected, sizeof(expected)) != 0) {
        std::printf("assertion format bytes differ\n");
        return 1;
    }
    std::printf("assert format cases passed\n");
    return 0;
}

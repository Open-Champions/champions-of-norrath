AsciiSpecial ascii_special[33] = {
    {0x8140, 0x20}, {0x8149, 0x21}, {0x8168, 0x22}, {0x8194, 0x23}, {0x8190, 0x24}, {0x8193, 0x25},
    {0x8195, 0x26}, {0x8166, 0x27}, {0x8169, 0x28}, {0x816a, 0x29}, {0x8196, 0x2a}, {0x817b, 0x2b},
    {0x8143, 0x2c}, {0x817c, 0x2d}, {0x8144, 0x2e}, {0x815e, 0x2f}, {0x8146, 0x3a}, {0x8147, 0x3b},
    {0x8171, 0x3c}, {0x8181, 0x3d}, {0x8172, 0x3e}, {0x8148, 0x3f}, {0x8197, 0x40}, {0x816d, 0x5b},
    {0x818f, 0x5c}, {0x816e, 0x5d}, {0x814f, 0x5e}, {0x8151, 0x5f}, {0x8165, 0x60}, {0x816f, 0x7b},
    {0x8162, 0x7c}, {0x8170, 0x7d}, {0x8150, 0x7e}};
AsciiRow ascii_table[3] = {{0x824f, 0x30}, {0x8260, 0x41}, {0x8281, 0x61}};

int main() {
    for (int c = 0; c < 256; ++c) {
        const unsigned short got = Ascii2Sjis__FUc(static_cast<unsigned char>(c));
        unsigned short want = 0;
        for (const AsciiSpecial& e : ascii_special) {
            if (e.ascii == c) want = e.sjis;
        }
        if (c >= 0x30 && c <= 0x39) want = 0x824f + (c - 0x30);
        if (c >= 0x41 && c <= 0x5a) want = 0x8260 + (c - 0x41);
        if (c >= 0x61 && c <= 0x7a) want = 0x8281 + (c - 0x61);
        if (got != want) return 1 + c;
    }
    std::puts("ascii2sjis passed");
    return 0;
}

int main() {
    int failures = 0;
    for (const Vector& v : vectors) {
        const unsigned got = bits(__ieee754_powf(flt(v.x), flt(v.y)));
        // 0/0 is the one place the EE and an IEEE host differ: the recorded
        // result 0xff800000 stands for "invalid", which the host reports as a NaN.
        const bool invalid = v.result == 0xff800000u && (got & 0x7fffffffu) > 0x7f800000u;
        if (got != v.result && !invalid) {
            if (failures < 20) std::printf("FAIL %08x %08x want %08x got %08x\n", v.x, v.y, v.result, got);
            ++failures;
        }
    }
    // Ordinary arguments agree with libm to a few ulp.
    for (float x = 0.37f; x < 40.0f; x *= 1.31f) {
        for (float y = -6.3f; y < 6.5f; y += 0.71f) {
            const float want = std::pow(x, y);
            const float got = __ieee754_powf(x, y);
            if (std::fabs(got - want) > std::fabs(want) * 4e-7f) {
                std::printf("LIBM %g^%g want %g got %g\n", x, y, want, got);
                ++failures;
            }
        }
    }
    std::printf("%s: %zu vectors, %d failures\n", failures ? "FAIL" : "ok",
                sizeof(vectors) / sizeof(vectors[0]), failures);
    return failures != 0;
}
